// Writes ui/src/styles/brand-tokens.css from the brand's DTCG token file (../brand/tokens/tokens.json).
//
//   node scripts/generate-tokens.mjs          (from app/; or `npm run generate:tokens` in app/ui)
//   node scripts/generate-tokens.mjs --check  exits 1 when brand-tokens.css is stale
//
// Every token becomes a CSS custom property named after its path (`semantic.text.primary` → `--semantic-text-primary`).
// Aliases (`{color.ebony}`) become `var(--color-ebony)`. Composite typography tokens expand into one property per
// field plus a `font` shorthand when the role has a size. An unknown `$type` throws, so a new kind of brand token is
// noticed here instead of silently dropped.
import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const appDir = resolve(dirname(fileURLToPath(import.meta.url)), "..");

export const tokensPath = resolve(appDir, "../brand/tokens/tokens.json");
export const outputPath = resolve(appDir, "ui/src/styles/brand-tokens.css");

const header = `/*
 * Generated by app/scripts/generate-tokens.mjs from brand/tokens/tokens.json. Do not edit.
 * Regenerate with \`npm run generate:tokens\` in app/ui; scripts/brand-tokens.test.ts fails when this file is stale.
 * Names follow the token paths. Use semantic roles before primitives (brand/tokens/README.md).
 */
`;

const aliasPattern = /^\{([^{}]+)\}$/;

function propertyName(path) {
  return `--${path.join("-")}`;
}

function comment(text) {
  return text === undefined ? "" : ` /* ${String(text).replaceAll("*/", "* /")} */`;
}

function alias(value) {
  const match = typeof value === "string" ? aliasPattern.exec(value) : null;
  return match === null ? null : `var(${propertyName(match[1].split("."))})`;
}

function dimension(value) {
  return `${String(value.value)}${value.unit}`;
}

function fontFamily(families) {
  return families.map((family) => (/^[\w-]+$/.test(family) ? family : `"${family}"`)).join(", ");
}

function scalar(type, value, path) {
  const referenced = alias(value);
  if (referenced !== null) {
    return referenced;
  }
  switch (type) {
    case "color":
    case "fontWeight":
    case "number":
      return String(value);
    case "dimension":
    case "duration":
      return dimension(value);
    case "fontFamily":
      return fontFamily(value);
    case "cubicBezier":
      return `cubic-bezier(${value.join(", ")})`;
    case "shadow":
      return [value.offsetX, value.offsetY, value.blur, value.spread].map(dimension).concat(scalar("color", value.color, path)).join(" ");
    default:
      throw new Error(`generate-tokens: unsupported $type "${String(type)}" at ${path.join(".")}`);
  }
}

function typography(token, path) {
  const value = token.$value;
  const brand = token.$extensions?.["com.fotohavn.brand"] ?? {};
  const name = propertyName(path);
  const lines = [];
  const field = (suffix, css, description) => lines.push(`  ${name}-${suffix}: ${css};${comment(description)}`);

  field("font-family", scalar("fontFamily", value.fontFamily, path), token.$description);
  if (value.fontSize !== undefined) field("font-size", dimension(value.fontSize));
  field("font-weight", scalar("fontWeight", value.fontWeight, path));
  if (value.letterSpacing !== undefined) field("letter-spacing", dimension(value.letterSpacing));
  field("line-height", String(value.lineHeight));
  field("font-style", brand.fontStyle ?? "normal");
  field("text-transform", brand.case === "uppercase" ? "uppercase" : "none");
  if (value.fontSize !== undefined) {
    field("font", `var(${name}-font-style) var(${name}-font-weight) var(${name}-font-size) / var(${name}-line-height) var(${name}-font-family)`);
  }
  return lines;
}

function* tokensIn(group, path) {
  for (const [key, child] of Object.entries(group)) {
    if (key.startsWith("$") || child === null || typeof child !== "object") {
      continue;
    }
    const childPath = [...path, key];
    if ("$value" in child) {
      yield { path: childPath, token: child, type: child.$type ?? group.$type };
    } else {
      yield* tokensIn(child, childPath);
    }
  }
}

/** The full text of brand-tokens.css for a parsed tokens.json, with LF line endings. */
export function renderBrandTokens(tokens) {
  const sections = [];
  for (const [group, value] of Object.entries(tokens)) {
    if (group.startsWith("$")) {
      continue;
    }
    const lines = [`  /* ${group} */`];
    for (const { path, token, type } of tokensIn(value, [group])) {
      if (type === "typography") {
        lines.push(...typography(token, path));
      } else {
        lines.push(`  ${propertyName(path)}: ${scalar(type, token.$value, path)};${comment(token.$description)}`);
      }
    }
    sections.push(lines.join("\n"));
  }
  return `${header}\n:root {\n${sections.join("\n\n")}\n}\n`;
}

export async function readTokens() {
  return JSON.parse(await readFile(tokensPath, "utf8"));
}

async function main(argv) {
  const css = renderBrandTokens(await readTokens());
  if (argv.includes("--check")) {
    const current = (await readFile(outputPath, "utf8").catch(() => "")).replaceAll("\r\n", "\n");
    if (current !== css) {
      console.error(`${outputPath} is stale. Run \`npm run generate:tokens\` in app/ui.`);
      process.exitCode = 1;
    }
    return;
  }
  await writeFile(outputPath, css, "utf8");
  console.log(`Wrote ${outputPath}`);
}

if (process.argv[1] !== undefined && import.meta.url === pathToFileURL(process.argv[1]).href) {
  await main(process.argv.slice(2));
}
