// @vitest-environment node
import { readFile } from "node:fs/promises";
import { describe, expect, it } from "vitest";
import { outputPath, readTokens, renderBrandTokens } from "../../scripts/generate-tokens.mjs";

describe("brand-tokens.css", () => {
  it("matches brand/tokens/tokens.json", async () => {
    const committed = (await readFile(outputPath, "utf8")).replaceAll("\r\n", "\n");
    const regenerated = renderBrandTokens(await readTokens());

    // On failure, run `npm run generate:tokens` and commit src/styles/brand-tokens.css.
    expect(committed).toBe(regenerated);
  });
});

describe("renderBrandTokens", () => {
  const css = renderBrandTokens({
    $description: "ignored",
    color: { ebony: { $type: "color", $value: "#1E1A17", $description: "Primary text */ ink" } },
    semantic: { text: { $type: "color", primary: { $value: "{color.ebony}" } } },
    font: {
      family: { sans: { $type: "fontFamily", $value: ["Manrope", "Segoe UI", "sans-serif"] } },
      weight: { semibold: { $type: "fontWeight", $value: 600 } },
    },
    typography: {
      eyebrow: {
        $type: "typography",
        $value: {
          fontFamily: "{font.family.sans}",
          fontSize: { value: 12, unit: "px" },
          fontWeight: "{font.weight.semibold}",
          letterSpacing: { value: 0.18, unit: "em" },
          lineHeight: 1.4,
        },
        $extensions: { "com.fotohavn.brand": { case: "uppercase" } },
      },
      emphasis: {
        $type: "typography",
        $value: { fontFamily: "{font.family.sans}", fontWeight: 400, lineHeight: 1.15 },
        $extensions: { "com.fotohavn.brand": { fontStyle: "italic", case: "sentence" } },
      },
    },
    shadow: {
      print: {
        $type: "shadow",
        $value: {
          color: "#2D211B24",
          offsetX: { value: 0, unit: "px" },
          offsetY: { value: 24, unit: "px" },
          blur: { value: 60, unit: "px" },
          spread: { value: 0, unit: "px" },
        },
      },
    },
    motion: {
      duration: { fast: { $type: "duration", $value: { value: 150, unit: "ms" } } },
      easing: { editorial: { $type: "cubicBezier", $value: [0.22, 1, 0.36, 1] } },
      scale: { max: { $type: "number", $value: 1.015 } },
    },
  });

  it("writes a do-not-edit header and one :root block", () => {
    expect(css).toMatch(/^\/\*\n \* Generated by app\/scripts\/generate-tokens\.mjs .* Do not edit\./);
    expect(css.match(/:root \{/g)).toHaveLength(1);
    expect(css).not.toContain("ignored");
  });

  it("names properties after token paths and resolves aliases to var()", () => {
    expect(css).toContain("  --color-ebony: #1E1A17; /* Primary text * / ink */");
    expect(css).toContain("  --semantic-text-primary: var(--color-ebony);");
    expect(css).toContain('  --font-family-sans: Manrope, "Segoe UI", sans-serif;');
    expect(css).toContain("  --font-weight-semibold: 600;");
  });

  it("expands typography roles, with case and italic from the brand extensions", () => {
    expect(css).toContain("  --typography-eyebrow-font-family: var(--font-family-sans);");
    expect(css).toContain("  --typography-eyebrow-font-size: 12px;");
    expect(css).toContain("  --typography-eyebrow-letter-spacing: 0.18em;");
    expect(css).toContain("  --typography-eyebrow-text-transform: uppercase;");
    expect(css).toContain("  --typography-eyebrow-font-style: normal;");
    expect(css).toContain(
      "  --typography-eyebrow-font: var(--typography-eyebrow-font-style) var(--typography-eyebrow-font-weight) var(--typography-eyebrow-font-size) / var(--typography-eyebrow-line-height) var(--typography-eyebrow-font-family);",
    );
    expect(css).toContain("  --typography-emphasis-font-style: italic;");
    expect(css).toContain("  --typography-emphasis-text-transform: none;");
    expect(css).not.toContain("--typography-emphasis-font-size");
    expect(css).not.toContain("--typography-emphasis-font:");
  });

  it("writes shadows, durations, easings, and numbers as CSS values", () => {
    expect(css).toContain("  --shadow-print: 0px 24px 60px 0px #2D211B24;");
    expect(css).toContain("  --motion-duration-fast: 150ms;");
    expect(css).toContain("  --motion-easing-editorial: cubic-bezier(0.22, 1, 0.36, 1);");
    expect(css).toContain("  --motion-scale-max: 1.015;");
  });

  it("refuses a token type it doesn't know", () => {
    expect(() => renderBrandTokens({ grid: { columns: { $type: "gridTemplate", $value: 12 } } })).toThrow(
      'generate-tokens: unsupported $type "gridTemplate" at grid.columns',
    );
  });
});
